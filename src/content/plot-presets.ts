import { z } from 'zod';

export const plotPresetSchema = z
  .object({
    id: z.string().regex(/^[a-z][a-z0-9-]*$/),
    name: z.string().min(1),
    expression: z.string().min(1).max(160),
    xMin: z.number().finite().min(-10000).max(10000),
    xMax: z.number().finite().min(-10000).max(10000),
    note: z.string().min(1),
  })
  .refine((value) => value.xMin < value.xMax, {
    message: '左端点必须小于右端点',
    path: ['xMax'],
  });

export type PlotPreset = z.infer<typeof plotPresetSchema>;

